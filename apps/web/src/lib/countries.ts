export function statesForCountry(code: string): Subdivision[] {
  return STATES_BY_COUNTRY[code] ?? [];
}

export function countryHasStates(code: string): boolean {
  return statesForCountry(code).length > 0;
}

/** Label for the subdivision field based on country. */
export function stateFieldLabel(code: string): string {
  if (code === "AE") return "Emirate";
  if (code === "US") return "State";
  if (code === "CA" || code === "AU") return "Province / Territory";
  if (code === "IN" || code === "PK") return "State / Province";
  if (code === "IE") return "County";
  if (code === "NZ" || code === "ZA" || code === "NP") return "Region";
  if (code === "BD") return "District";
  return "State / Province / Region";
}
